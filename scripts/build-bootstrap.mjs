#!/usr/bin/env node
// Builds the committed one-command bootstraps from their sources (v1.7.0, 2026-10-21):
//   bootstrap/src/<os>.sh + bootstrap/src/common.sh  ->  bootstrap/<os>.sh
// Why generated: `curl -fsSL …/bootstrap/macos.sh | bash` receives ONE file, so the part shared with
// ubuntu.sh cannot be a sourced sibling. Inlining it at build time keeps a single copy in the repo and
// no second download at run time (a raw.githubusercontent.com cache could serve a mismatched one).
// Usage: node scripts/build-bootstrap.mjs            write the outputs
//        node scripts/build-bootstrap.mjs --check    exit 1 when a committed output is stale (CI)
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BOOTSTRAP_OSES = ['ubuntu', 'macos'];
// The include line, plus the shellcheck directive above it that only makes sense in the source.
const INCLUDE_LINE = /^(?:# shellcheck source=common\.sh\n)?.*# @include common\.sh[ \t]*$/m;
const SET_LINE = /^set -euo pipefail$/m;

/** File text with LF line endings. Example: readLf('/repo/bootstrap/src/common.sh') -> '# Shared…\n' */
function readLf(file) {
  return readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
}

/** The generated script for one OS. Example: buildBootstrapScript('macos') -> '#!/usr/bin/env bash\n…' */
export function buildBootstrapScript(os) {
  const entry = readLf(path.join(ROOT, 'bootstrap', 'src', `${os}.sh`));
  if (!INCLUDE_LINE.test(entry) || !SET_LINE.test(entry)) {
    throw new Error(`bootstrap/src/${os}.sh: expected one "set -euo pipefail" line and one "# @include common.sh" line`);
  }
  const common = readLf(path.join(ROOT, 'bootstrap', 'src', 'common.sh')).trimEnd();
  const notice = `# GENERATED by scripts/build-bootstrap.mjs from bootstrap/src/${os}.sh + bootstrap/src/common.sh: edit those, then run \`npm run build:bootstrap\`.`;
  // Replacer functions, not strings: the bash text is full of `$1`/`$&`, which String#replace would expand.
  return entry.replace(SET_LINE, (line) => `${line}\n${notice}`).replace(INCLUDE_LINE, () => common);
}

/** Write every stale output, or with `check` only list them. Example: syncBootstrapScripts(true) -> ['bootstrap/macos.sh'] */
function syncBootstrapScripts(check) {
  const stale = [];
  for (const os of BOOTSTRAP_OSES) {
    const rel = `bootstrap/${os}.sh`;
    const want = buildBootstrapScript(os);
    const have = existsSync(path.join(ROOT, rel)) ? readLf(path.join(ROOT, rel)) : null;
    if (have === want) continue;
    stale.push(rel);
    if (!check) writeFileSync(path.join(ROOT, rel), want);
  }
  return stale;
}

const checkOnly = process.argv.includes('--check');
const stale = syncBootstrapScripts(checkOnly);
if (checkOnly && stale.length) {
  console.error(`bootstrap: stale generated scripts: ${stale.join(', ')}; expected them rebuilt from bootstrap/src (run npm run build:bootstrap)`);
  process.exit(1);
}
console.log(stale.length ? `bootstrap: wrote ${stale.join(', ')}` : 'bootstrap: generated scripts are up to date');
